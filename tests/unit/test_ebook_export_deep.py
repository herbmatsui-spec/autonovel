def _make_series(genre: str = "ハイファンタジー (R15)", episode_count: int = 2) -> SeriesResult:
    episodes = []
    for i in range(episode_count):
        content = (
            f"エピソード{i+1}の本文\n\n主人公は行動した。\n\n「セリフです」\n\n"
            f"衝撃の展開！\n"
        )
        episodes.append(
            EpisodeResult(
                episode_num=i + 1,
                title=f"テスト話{i+1}",
                content=content,
                word_count=len(content),
                audit_score=85.0,
                audit_passed=True,
                rewrite_count=0,
                spice_elements=[
                    SpiceElement(type="unique_metaphor", text="例え", position=0, priority="low")
                ],
                metadata={},
            )
        )
    return SeriesResult(
        genre=genre,
        title="テストシリーズ",
        concept="異世界転生チート",
        total_episodes=episode_count,
        episodes=episodes,
        bible={"protagonist": "テスト主人公"},
        plot_outline=[{"episode": 1, "title": "プロローグ", "summary": "物語の始まり"}],
        metadata={"prologue": "プロローグ本文", "epilogue": "エピローグ本文"},
    )


