class TestEbookContentProcessor:
    @pytest.fixture
    def processor(self) -> EbookContentProcessor:
        return EbookContentProcessor("ハイファンタジー (R15)")

    def test_create_chapters_with_prologue_epilogue(self, processor):
        series = _make_series()
        chapters = processor.create_chapters(series)
        # プロローグ + 2話 + エピローグ
        assert len(chapters) == 4
        assert chapters[0].title == "プロローグ"
        assert chapters[0].episode_num == 0
        assert chapters[1].title == "テスト話1"
        assert chapters[2].title == "テスト話2"
        assert chapters[3].title == "エピローグ"
        assert chapters[3].episode_num == 3

    def test_create_chapters_without_prologue_epilogue(self):
        series = _make_series()
        series.metadata = {}
        processor = EbookContentProcessor("test")
        chapters = processor.create_chapters(series)
        assert len(chapters) == 2

    def test_format_content_paragraphs(self, processor):
        text = "段落1\n\n段落2"
        result = processor._format_content(text)
        assert "<p>段落1</p>" in result
        assert "<p>段落2</p>" in result

    def test_format_content_dialogue(self, processor):
        text = "「セリフです」"
        result = processor._format_content(text)
        assert '<p class="dialogue">' in result

    def test_format_content_emphasis(self, processor):
        text = "衝撃の展開！"
        result = processor._format_content(text)
        assert '<p class="emphasis">' in result

    def test_format_content_empty_paragraph(self, processor):
        result = processor._format_content("\n\n\n")
        assert result == ""

    def test_escape_html(self, processor):
        raw = '<a href="x">&'
        result = processor._escape_html(raw)
        # & と < がエスケープされることを検証
        assert chr(60) not in result  # < は残らない
        assert chr(38) in result      # & エンティティが使われる
        assert "lt;" in result


    def test_generate_css(self, processor):
        css = processor.generate_css()
        assert "font-family" in css
        assert "body" in css


