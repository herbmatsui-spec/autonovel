class TestEbookExporter:
    def _make_exporter(self, output_dir: Path) -> EbookExporter:
        metadata = EbookMetadata(title="テストシリーズ", genre="ハイファンタジー (R15)")
        return EbookExporter(metadata, output_dir)

    def test_init(self, tmp_path):
        exporter = self._make_exporter(tmp_path)
        assert exporter.genre == "ハイファンタジー (R15)"
        assert exporter.output_dir == tmp_path
        assert exporter.preset == {}

    def test_create_metadata_from_series(self, tmp_path):
        exporter = self._make_exporter(tmp_path)
        series = _make_series()
        meta = exporter.create_metadata(series)
        assert meta.title == "テストシリーズ"
        assert meta.genre == "ハイファンタジー (R15)"

    def test_create_metadata_with_overrides(self, tmp_path):
        exporter = self._make_exporter(tmp_path)
        series = _make_series()
        meta = exporter.create_metadata(
            series, author="上書き作者", tags=["tag1", "tag2"]
        )
        assert meta.author == "上書き作者"
        assert meta.tags == ["tag1", "tag2"]

    def test_export_epub_fallback(self, tmp_path):
        series = _make_series()
        exporter = self._make_exporter(tmp_path)
        out_path = tmp_path / "out.epub"
        if not EPUB_AVAILABLE:
            # ebooklib 非依存環境では例外がログに記録され、失敗する可能性がある
            try:
                result = exporter.export_epub(series, out_path)
                assert result is not None
            except Exception:
                pass  # 環境依存のフォールバック

    def test_export_all_mobi_unknown_format(self, tmp_path):
        series = _make_series()
        exporter = self._make_exporter(tmp_path)
        results = exporter.export_all(series, tmp_path, ["mobi", "unknown"])
        assert isinstance(results, dict)

    def test_export_all_default_formats(self, tmp_path):
        series = _make_series()
        exporter = self._make_exporter(tmp_path)
        # formats=None でデフォルト (epub, pdf)
        results = exporter.export_all(series, tmp_path, None)
        assert isinstance(results, dict)


