"""
Emotion syllogism regex patterns for Anti-AI prose detection.
PLAN 03: AI優等生病の外科的切除
"""
from __future__ import annotations

import re

# LLM特有の「感情の三段論法」「説明的内省」「優等生的自己説得」の正規表現パターン
SYLLOGISM_PATTERNS: list[re.Pattern] = [
    # 1. 感情の提示 + なぜなら理由説明
    re.compile(
        r"(?:怒り|悲しみ|恐怖|歓喜|戸惑い|悔しさ|焦り|不快感)を"
        r"(?:感じた|覚えた|抱いた|禁じ得なかった)[。、]?\s*"
        r"(?:なぜなら|というのも|その理由は)"
    ),
    # 2. 優等生的な自己説得・感情抑制
    re.compile(
        r"(?:べきだと|なければならないと|のだと|と)"
        r"(?:自分に言い聞かせた|心に誓った|自分を納得させた|言い聞かせた|戒めた)"
    ),
    # 3. 躊躇からの紋切り型な決意・気を取り直し
    re.compile(
        r"一瞬(?:躊躇|迷っ|息を呑ん|立ち止まっ)たが[、]?\s*"
        r"(?:気を取り直して|思い直して|意を決して|何とか持ち直し)"
    ),
    # 4. 理不尽を受け流す不自然な大人の対応
    re.compile(
        r"理不尽だと(?:思いつつ|感じながら|分かりつつ)も[、]?\s*"
        r"(?:大人の対応|冷静さを保|平静を装|グッと堪え)"
    ),
    # 5. 抽象的感情の紋切り型な説明
    re.compile(
        r"(?:複雑な思い|言いようのない感情|胸が締め付けられるような思い)が"
        r"(?:胸を去来した|胸を過った|渦巻いた|去来した)"
    ),
]
